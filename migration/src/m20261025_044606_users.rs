//! The `users` table: backend3's admin accounts (ADR 0006 §7, ADR 0009).
//!
//! This migration creates the complete column set of ADR 0006 §7, so no later
//! slice alters the table: the sign-in columns, the two-factor columns, the
//! anonymisation marker and the audit columns of ADR 0011 §2. Loco's starter
//! columns for API keys, e-mail verification, mailed reset tokens and magic
//! links are deliberately absent: backend3 mounts none of the starter's auth
//! routes and sends no mail (ADR 0006 §4, parity AUTH-06).
//!
//! Loco's `create_table` writes the columns, including the `timestamptz`
//! `created_at` and `updated_at` pair with a `CURRENT_TIMESTAMP` default
//! (ADR 0009, ADR 0010). It cannot express the rest, so [`CONSTRAINTS`] adds
//! it as plain SQL with `snake_case` names that need no quoting (ADR 0009):
//!
//! - `created_by`, `updated_by` and `deleted_by` are self-references with
//!   `ON DELETE RESTRICT`. Loco's nullable references would use
//!   `ON DELETE SET NULL`, which would erase authorship. A user row is never
//!   deleted: permanent delete anonymises it so every reference stays valid
//!   (ADR 0011 §6, ADR 0006 §7), and `RESTRICT` makes the database hold the
//!   application to that.
//! - Each of those foreign keys has an index, because PostgreSQL does not
//!   index foreign-key columns by itself (ADR 0009, "Constraints").
//! - The e-mail address is unique on `lower(email)` across all rows, trashed
//!   ones included, so a trashed account keeps its address until it is
//!   anonymised (ADR 0009, ADR 0011 §3). The finder for sign-in compares
//!   `lower(email)` too, so it can use this index and always agrees with it.
//!   `lower()` folds by the database's default collation: accented letters
//!   too under the `en_US.utf8` locale of the official PostgreSQL image, only
//!   ASCII under the C locale. `hu_icu` is not used here: ADR 0020 accepts
//!   ICU upgrades because no index uses that collation ("Consequences").
//! - The two CHECK constraints of ADR 0006 §7, verbatim, fix the shape of an
//!   anonymised row.

use loco_rs::schema::{ColType, create_table, drop_table};
use sea_orm_migration::prelude::*;

/// Creates the `users` table with its constraints and indexes.
#[derive(DeriveMigrationName)]
pub struct Migration;

/// The columns of `users` other than Loco's `created_at` and `updated_at`,
/// in the order of ADR 0006 §7.
///
/// `ColType::*Null` columns are nullable; the others are `NOT NULL`.
/// `id` renders as `bigint GENERATED BY DEFAULT AS IDENTITY`, which accepts
/// the importer's explicit legacy ids (ADR 0009).
fn columns() -> Vec<(&'static str, ColType)> {
    vec![
        ("id", ColType::PkAuto),
        // The JWT claim key (ADR 0006 §1): `uuid NOT NULL UNIQUE`.
        ("pid", ColType::UuidUniq),
        // NULL only on anonymised rows (the CHECKs below).
        ("email", ColType::TextNull),
        ("name", ColType::Text),
        // Argon2id PHC string, or the imported bcrypt string until the first
        // sign-in; NULL while pending and after anonymisation.
        ("password_hash", ColType::TextNull),
        ("must_change_password", ColType::BooleanWithDefault(false)),
        (
            "temp_password_expires_at",
            ColType::TimestampWithTimeZoneNull,
        ),
        // Revocation counter (ADR 0006 §2).
        ("token_version", ColType::IntegerWithDefault(0)),
        ("active", ColType::BooleanWithDefault(true)),
        ("last_login_at", ColType::TimestampWithTimeZoneNull),
        // Nonce, ciphertext and tag of the TOTP secret (ADR 0006 §6); `Blob`
        // renders as `bytea` on PostgreSQL.
        ("totp_secret_encrypted", ColType::BlobNull),
        ("totp_enabled_at", ColType::TimestampWithTimeZoneNull),
        ("totp_last_step", ColType::BigIntegerNull),
        ("anonymised_at", ColType::TimestampWithTimeZoneNull),
        // Audit columns of ADR 0011 §2; their foreign keys are in
        // CONSTRAINTS.
        ("created_by", ColType::BigIntegerNull),
        ("updated_by", ColType::BigIntegerNull),
        ("deleted_at", ColType::TimestampWithTimeZoneNull),
        ("deleted_by", ColType::BigIntegerNull),
    ]
}

/// Statements that run after the table exists, in order. The foreign keys
/// and their indexes follow PostgreSQL's own `<table>_<column>_<suffix>`
/// pattern; the CHECKs and the expression index, for which PostgreSQL would
/// generate `users_check`, `users_check1` and `users_lower_idx`, get
/// descriptive `snake_case` names instead, so an error message says which
/// rule refused the row.
const CONSTRAINTS: &[&str] = &[
    "ALTER TABLE users ADD CONSTRAINT users_created_by_fkey \
     FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT",
    "ALTER TABLE users ADD CONSTRAINT users_updated_by_fkey \
     FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT",
    "ALTER TABLE users ADD CONSTRAINT users_deleted_by_fkey \
     FOREIGN KEY (deleted_by) REFERENCES users (id) ON DELETE RESTRICT",
    "CREATE INDEX users_created_by_idx ON users (created_by)",
    "CREATE INDEX users_updated_by_idx ON users (updated_by)",
    "CREATE INDEX users_deleted_by_idx ON users (deleted_by)",
    "CREATE UNIQUE INDEX users_lower_email_key ON users (lower(email))",
    "ALTER TABLE users ADD CONSTRAINT users_email_present \
     CHECK (email IS NOT NULL OR anonymised_at IS NOT NULL)",
    "ALTER TABLE users ADD CONSTRAINT users_anonymised_shape \
     CHECK (anonymised_at IS NULL OR (email IS NULL AND password_hash IS NULL \
     AND totp_secret_encrypted IS NULL AND NOT active AND deleted_at IS NOT NULL))",
];

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, m: &SchemaManager) -> Result<(), DbErr> {
        create_table(m, "users", &columns(), &[]).await?;
        let db = m.get_connection();
        for statement in CONSTRAINTS {
            db.execute_unprepared(statement).await?;
        }
        Ok(())
    }

    /// Drops the table; its constraints and indexes go with it.
    async fn down(&self, m: &SchemaManager) -> Result<(), DbErr> {
        drop_table(m, "users").await
    }
}
