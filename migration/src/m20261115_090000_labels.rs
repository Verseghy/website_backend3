//! The `labels` table: the post labels, „címkék” (ADR 0009, ADR 0011;
//! parity LBL-01).
//!
//! The table carries the whole column set of ADR 0009 and ADR 0011 §2 from
//! the start, so the later label slices (the writes, the trash, the import)
//! add no column: `id`, `name` and `color`, the `timestamptz` pair
//! `created_at` and `updated_at`, which Loco's `create_table` writes with a
//! `CURRENT_TIMESTAMP` default (ADR 0010; research: DECISIONS R15, D90),
//! and the audit and soft-delete columns `created_by`, `updated_by`,
//! `deleted_at` and `deleted_by`. Loco's `create_table` cannot express the
//! rest, so [`CONSTRAINTS`] adds it as plain SQL with `snake_case` names
//! that need no quoting (ADR 0009):
//!
//! - `color` is `#rrggbb`: `CHECK (color ~ '^#[0-9A-Fa-f]{6}$')`, the colour
//!   rule of ADR 0009 ("Column types"), which every legacy value meets. In
//!   PostgreSQL's advanced regular expressions `$` matches only at the end
//!   of the text, so a trailing line break is refused too.
//! - `created_by`, `updated_by` and `deleted_by` reference `users (id)` with
//!   `ON DELETE RESTRICT`, as the `users` migration's own audit columns do:
//!   accounts are anonymised, never deleted, and keep every reference
//!   (ADR 0011 §6, ADR 0006 §7). Each has an index, because PostgreSQL does
//!   not index foreign-key columns by itself (ADR 0009, "Constraints").
//! - A label name is unique on `lower(name)` among the rows that are not in
//!   the trash (ADR 0009, "Constraints"; ADR 0011 §3): the partial unique
//!   index `labels_live_lower_name_key`. A trashed label keeps its name
//!   without blocking a new live one, and its restore is refused while a
//!   live label holds the name. `lower()` folds by the database's default
//!   collation, as the `users` e-mail key does; `hu_icu` stays out of every
//!   index, because ADR 0020 accepts that an ICU upgrade may shift its
//!   order only while no index depends on it ("Consequences").
//!
//! `name` has no length limit in the schema: ADR 0009 keeps length limits in
//! domain validation (the label name's 64 characters), which the label
//! writes check before they reach the table. Lists sort the name with an
//! explicit `COLLATE hu_icu` in the query (ADR 0020 §4), not with a column
//! collation, for the same reason as the index.

use loco_rs::schema::{ColType, create_table, drop_table};
use sea_orm_migration::prelude::*;

/// Creates the `labels` table with its constraints and indexes.
#[derive(DeriveMigrationName)]
pub struct Migration;

/// The columns of `labels` other than Loco's `created_at` and `updated_at`.
///
/// `ColType::*Null` columns are nullable; the others are `NOT NULL`. `id`
/// renders as `bigint GENERATED BY DEFAULT AS IDENTITY`, which accepts the
/// importer's explicit legacy ids (ADR 0009, primary-key rules 1 and 2).
fn columns() -> Vec<(&'static str, ColType)> {
    vec![
        ("id", ColType::PkAuto),
        ("name", ColType::Text),
        // `#rrggbb`, checked by `labels_color_format` below.
        ("color", ColType::Text),
        // Audit columns of ADR 0011 §2; their foreign keys are in
        // CONSTRAINTS.
        ("created_by", ColType::BigIntegerNull),
        ("updated_by", ColType::BigIntegerNull),
        ("deleted_at", ColType::TimestampWithTimeZoneNull),
        ("deleted_by", ColType::BigIntegerNull),
    ]
}

/// Statements that run after the table exists, in order. The foreign keys
/// and their indexes follow PostgreSQL's own `<table>_<column>_<suffix>`
/// pattern, as the `users` migration's do; the CHECK and the partial
/// expression index get descriptive names instead of PostgreSQL's
/// `labels_color_check` and `labels_lower_idx`, so a refusal says which rule
/// refused the row.
const CONSTRAINTS: &[&str] = &[
    "ALTER TABLE labels ADD CONSTRAINT labels_color_format \
     CHECK (color ~ '^#[0-9A-Fa-f]{6}$')",
    "ALTER TABLE labels ADD CONSTRAINT labels_created_by_fkey \
     FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT",
    "ALTER TABLE labels ADD CONSTRAINT labels_updated_by_fkey \
     FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT",
    "ALTER TABLE labels ADD CONSTRAINT labels_deleted_by_fkey \
     FOREIGN KEY (deleted_by) REFERENCES users (id) ON DELETE RESTRICT",
    "CREATE INDEX labels_created_by_idx ON labels (created_by)",
    "CREATE INDEX labels_updated_by_idx ON labels (updated_by)",
    "CREATE INDEX labels_deleted_by_idx ON labels (deleted_by)",
    "CREATE UNIQUE INDEX labels_live_lower_name_key ON labels (lower(name)) \
     WHERE deleted_at IS NULL",
];

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, m: &SchemaManager) -> Result<(), DbErr> {
        create_table(m, "labels", &columns(), &[]).await?;
        let db = m.get_connection();
        for statement in CONSTRAINTS {
            db.execute_unprepared(statement).await?;
        }
        Ok(())
    }

    /// Drops the table; its constraints and indexes go with it.
    async fn down(&self, m: &SchemaManager) -> Result<(), DbErr> {
        drop_table(m, "labels").await
    }
}
