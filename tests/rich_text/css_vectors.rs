//! The stability test of `css-vectors.jsonl` (editor.md §3.9, §13.6,
//! "Differential CSS").
//!
//! The vector file is the contract between the server's grammar and the
//! admin's TypeScript `canonicalStyle`: every line is an input and the one
//! spelling the server stores for it. A change to any output is a change to
//! that contract, and under editor.md §3 usually a policy change, so it must
//! never pass unnoticed. This test keeps the whole file as an insta
//! snapshot, `snapshots/css_vectors.snap`: a PR that changes an output
//! fails here until it updates the snapshot, and the diff shows every line
//! that changed. Review the `.snap.new` that insta writes beside it
//! (`cargo insta review`) and commit it with the change. CI sets
//! `INSTA_UPDATE=no`, so there a mismatch only fails.
//!
//! The snapshot lives under `tests/` because `src/domain/` reads no files
//! (ADR 0008). The `rich_text_manifest` task writes the file the admin
//! imports, `admin/src/rich-text/css-vectors.jsonl`, from the same
//! generator (editor.md §3.9).

use backend3::domain::rich_text::css::vectors::{CASES, css_vectors_jsonl};

/// The header line of the committed snapshot, for whoever meets it in a diff.
const DESCRIPTION: &str = "css-vectors.jsonl, generated by \
     backend3::domain::rich_text::css::vectors (editor.md §3.9, §13.6). The admin's \
     canonicalStyle must write the same output for every line.";

#[test]
fn the_vector_file_matches_the_snapshot() {
    let file = css_vectors_jsonl();
    // Two runs write the same bytes: nothing in the generator depends on a
    // hash seed or on the process.
    assert_eq!(file, css_vectors_jsonl());
    assert_eq!(file.lines().count(), CASES.len());
    // The plain file name: insta would otherwise prefix it with the module
    // path of the `mod` test crate.
    insta::with_settings!({
        prepend_module_to_snapshot => false,
        description => DESCRIPTION,
        omit_expression => true,
    }, {
        insta::assert_snapshot!("css_vectors", file);
    });
}
