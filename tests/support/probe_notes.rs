//! `probe_notes`: a test-only admin-editable entity, built the way every
//! entity slice builds its own (recipe 2 of the project skill), so the
//! revisions model and the safety-net helper ([`super::safety_net`]) are
//! proven before the first real entity exists.
//!
//! [`create_table`] creates its table in the test's own database: the audit
//! columns of ADR 0011 §2 (with PostgreSQL's clock, research: DECISIONS R15,
//! D90) and three editable fields. No migration creates it, so it never
//! reaches the schema snapshot. [`ProbeNoteRevision`] is its snapshot type at
//! version 2, with the one upcaster step from version 1, which called
//! `title` `name`. [`create`] and [`update`] are its write methods: the row
//! and then [`backend3::models::revisions::record_save`], in the caller's
//! transaction. [`ProbeNotes`] runs them for the safety-net helper.
//!
//! The values are invented.

use backend3::{
    domain::{
        activity::Actor,
        revision::{Reason, RevisionSnapshot, SnapshotObject, UpcastStep, UpcastStepError},
    },
    models::revisions::{Save, Saved, record_save},
};
use loco_rs::model::ModelResult;
use sea_orm::{
    ConnectionTrait, DatabaseConnection, DatabaseTransaction, DbBackend, Statement, Value,
};
use serde::{Deserialize, Serialize};

use super::safety_net::SafetyNetEntity;

/// The test-only table, as an entity migration would create it: a `bigint`
/// identity id, the four audit columns with `ON DELETE RESTRICT` keys
/// (recipe 2 step 1), and the fields of [`ProbeNoteRevision`].
const CREATE_TABLE: &str = "CREATE TABLE probe_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    body text,
    color text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by bigint REFERENCES users (id) ON DELETE RESTRICT,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by bigint REFERENCES users (id) ON DELETE RESTRICT
)";

/// Creates the `probe_notes` table in the test's database.
///
/// - `db`: the test's pool (`ctx.db`).
pub async fn create_table(db: &DatabaseConnection) {
    db.execute_unprepared(CREATE_TABLE)
        .await
        .expect("create probe_notes");
}

/// The revision snapshot of a probe note: its three editable fields.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProbeNoteRevision {
    /// The title; `name` in version 1.
    pub title: String,
    /// The body, if any.
    pub body: Option<String>,
    /// The colour, `#rrggbb`.
    pub color: String,
}

/// Version 1 to 2: `name` became `title`.
fn rename_name_to_title(mut v1: SnapshotObject) -> Result<SnapshotObject, UpcastStepError> {
    let name = v1.remove("name").ok_or(UpcastStepError::MissingField {
        field: "name".to_owned(),
    })?;
    v1.insert("title".to_owned(), name);
    Ok(v1)
}

impl RevisionSnapshot for ProbeNoteRevision {
    const ENTITY_TYPE: &'static str = "probe_notes";
    const SCHEMA_VERSION: i32 = 2;
    const FIELDS: &'static [&'static str] = &["title", "body", "color"];
    const UPCASTS: &'static [UpcastStep] = &[UpcastStep {
        from: 1,
        apply: rename_name_to_title,
    }];
}

/// The one value of the first row that `statement` returns.
async fn one<C: ConnectionTrait, T: sea_orm::TryGetable>(db: &C, statement: Statement) -> T {
    let sql = statement.sql.clone();
    db.query_one_raw(statement)
        .await
        .expect(&sql)
        .expect("one row")
        .try_get_by_index(0)
        .expect(&sql)
}

/// Inserts the row of a new note as `actor`, with no revision or entry,
/// and returns its id: the first half of [`create`].
///
/// - `txn`: the save's transaction.
/// - `actor`: who creates it; `created_by` and `updated_by` are its user id.
/// - `snapshot`: the note's fields.
pub async fn insert_row(
    txn: &DatabaseTransaction,
    actor: Actor,
    snapshot: &ProbeNoteRevision,
) -> i64 {
    one(
        txn,
        Statement::from_sql_and_values(
            DbBackend::Postgres,
            "INSERT INTO probe_notes (title, body, color, created_by, updated_by) \
             VALUES ($1, $2, $3, $4, $4) RETURNING id",
            [
                Value::from(snapshot.title.clone()),
                Value::from(snapshot.body.clone()),
                Value::from(snapshot.color.clone()),
                Value::from(actor.user_id()),
            ],
        ),
    )
    .await
}

/// Writes `snapshot` over note `id` as `actor`, with `updated_at` from
/// PostgreSQL's clock, and no revision or entry: the first half of
/// [`update`].
///
/// - `txn`: the save's transaction.
/// - `actor`: who saves it; `updated_by` is its user id.
/// - `id`: the note.
/// - `snapshot`: its fields after the save.
pub async fn update_row(
    txn: &DatabaseTransaction,
    actor: Actor,
    id: i64,
    snapshot: &ProbeNoteRevision,
) {
    txn.execute_raw(Statement::from_sql_and_values(
        DbBackend::Postgres,
        "UPDATE probe_notes SET title = $1, body = $2, color = $3, \
         updated_at = CURRENT_TIMESTAMP, updated_by = $4 WHERE id = $5",
        [
            Value::from(snapshot.title.clone()),
            Value::from(snapshot.body.clone()),
            Value::from(snapshot.color.clone()),
            Value::from(actor.user_id()),
            Value::from(id),
        ],
    ))
    .await
    .expect("update the probe note");
}

/// The snapshot of note `id` as stored now.
///
/// - `db`: any connection.
/// - `id`: the note.
pub async fn snapshot_of<C: ConnectionTrait>(db: &C, id: i64) -> ProbeNoteRevision {
    let row = db
        .query_one_raw(Statement::from_sql_and_values(
            DbBackend::Postgres,
            "SELECT title, body, color FROM probe_notes WHERE id = $1",
            [id.into()],
        ))
        .await
        .expect("read the probe note")
        .expect("the probe note exists");
    ProbeNoteRevision {
        title: row.try_get_by_index(0).expect("title"),
        body: row.try_get_by_index(1).expect("body"),
        color: row.try_get_by_index(2).expect("color"),
    }
}

/// Creates a note as `actor` the way an entity's create method does: the
/// row, then its revision 1 and its `create` entry, labelled with the title
/// (ADR 0011 §7).
///
/// - `txn`: the save's transaction.
/// - `actor`: who creates it.
/// - `snapshot`: the note's fields.
/// - `request_id`: the request's id, if any.
///
/// # Errors
///
/// Every error of [`record_save`].
pub async fn create(
    txn: &DatabaseTransaction,
    actor: Actor,
    snapshot: &ProbeNoteRevision,
    request_id: Option<&str>,
) -> ModelResult<(i64, Saved)> {
    let id = insert_row(txn, actor, snapshot).await;
    let saved = record_save(
        txn,
        actor,
        Save {
            label: Some(snapshot.title.clone()),
            request_id: request_id.map(str::to_owned),
            ..Save::new(id, Reason::Create, snapshot)
        },
    )
    .await?;
    Ok((id, saved))
}

/// Saves note `id` as `actor` the way an entity's update method does: the
/// row with its audit columns, then the next revision and the `update` (or
/// `revert`) entry with the changed field names (ADR 0011 §7).
///
/// - `txn`: the save's transaction.
/// - `actor`: who saves it.
/// - `id`: the note.
/// - `reason`: [`Reason::Update`] or [`Reason::Revert`].
/// - `snapshot`: its fields after the save.
///
/// # Errors
///
/// Every error of [`record_save`].
pub async fn update(
    txn: &DatabaseTransaction,
    actor: Actor,
    id: i64,
    reason: Reason,
    snapshot: &ProbeNoteRevision,
) -> ModelResult<Saved> {
    update_row(txn, actor, id, snapshot).await;
    record_save(
        txn,
        actor,
        Save {
            label: Some(snapshot.title.clone()),
            ..Save::new(id, reason, snapshot)
        },
    )
    .await
}

/// A first note, as [`ProbeNotes`] creates it.
#[must_use]
pub fn first_note() -> ProbeNoteRevision {
    ProbeNoteRevision {
        title: "Próba jegyzet".to_owned(),
        body: Some("<p>Első változat</p>".to_owned()),
        color: "#336699".to_owned(),
    }
}

/// The note `current` after one more [`ProbeNotes`] update: a new title and
/// the other colour, the body unchanged.
#[must_use]
pub fn next_note(current: &ProbeNoteRevision) -> ProbeNoteRevision {
    ProbeNoteRevision {
        title: format!("{} +", current.title),
        color: if current.color == "#336699" {
            "#993366".to_owned()
        } else {
            "#336699".to_owned()
        },
        ..current.clone()
    }
}

/// The probe entity under the safety-net helper: [`create`] of
/// [`first_note`], and [`update`] to [`next_note`], which changes `color`
/// and `title`.
pub struct ProbeNotes;

impl SafetyNetEntity for ProbeNotes {
    type Snapshot = ProbeNoteRevision;

    async fn create(&self, txn: &DatabaseTransaction, actor: Actor) -> ModelResult<i64> {
        create(txn, actor, &first_note(), Some("probe-request"))
            .await
            .map(|(id, _)| id)
    }

    async fn update(&self, txn: &DatabaseTransaction, actor: Actor, id: i64) -> ModelResult<()> {
        let next = next_note(&snapshot_of(txn, id).await);
        update(txn, actor, id, Reason::Update, &next)
            .await
            .map(|_| ())
    }

    fn changed_fields(&self) -> Vec<String> {
        vec!["color".to_owned(), "title".to_owned()]
    }

    async fn snapshot(&self, db: &DatabaseConnection, id: i64) -> ProbeNoteRevision {
        snapshot_of(db, id).await
    }

    fn label(&self, snapshot: &ProbeNoteRevision) -> Option<String> {
        Some(snapshot.title.clone())
    }
}
