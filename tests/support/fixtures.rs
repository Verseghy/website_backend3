//! The named fixtures of the `/api/v1` specification tests (public-api.md
//! §17.1, ADR 0019 §2) and the soft-deleted twin of every public row (ADR
//! 0011, "What must be true in code and tests").
//!
//! backend2's retirement is proven by new tests written from public-api.md,
//! not by a comparison with backend2, so every production-only data shape
//! must exist as a named fixture (ADR 0019 §2). A fixture is registered in
//! [`FIXTURES`] under the name that the §17.1 tables give it, by the
//! endpoint slice whose tests need it, and a request test loads the
//! fixtures it reads by name with [`load`]. The rules of the mechanism:
//!
//! - **Rows are written directly**, through the models and their
//!   transaction or with SQL, never through `/api/admin`: a public endpoint
//!   test must not depend on the admin API, which has its own tests, and
//!   some shapes are ones the admin refuses (a trashed dish still linked to
//!   a day, §17.1). All content is invented (public-api.md §16.2).
//! - **Explicit ids, below [`TWIN_ID_OFFSET`].** Every row a fixture writes
//!   gets an explicit id, so that the samples of the global suite
//!   (`tests/support/public_samples.rs`) and the tests can name rows
//!   without reading them back. The identity columns are `GENERATED BY
//!   DEFAULT` (ADR 0009), so explicit ids are accepted; after the fixtures
//!   ran, [`load`] moves every identity sequence past the largest id below
//!   the offset, so a row a test creates afterwards gets a fresh id.
//! - **Every public row has a soft-deleted twin.** For each row of a
//!   trashable public type (post, draft with a preview token, label,
//!   author, page, menu item, dish, canteen day, event, colleague and each
//!   release-1 type, ADR 0011 §1), its fixture also writes a copy in the
//!   trash with [`FixtureWriter::twin`]: the same values, `deleted_at` set
//!   to [`TWIN_DELETED_AT`], and the id `id + TWIN_ID_OFFSET`. No live row
//!   has an id in that range, and [`load`] refuses one, so every id from
//!   [`TWIN_ID_OFFSET`] up is a trashed row, whatever its table. A public
//!   answer must never contain one: [`twin_ids_in`] finds any, and the
//!   global suite checks every `200` with it. So that this check cannot
//!   pass on an answer that lists nothing, the suite also asks that each
//!   route's base answer list a row ([`row_ids_in`]) whose twin one of the
//!   route's own fixtures wrote ([`Twin::fixture`]). Each endpoint test still
//!   asserts what its own rule says about the twins (a `404` for the twin's
//!   id, the full order of a list without them).
//!
//! The ids and names a fixture uses are its own; [`load`] runs all of them
//! in one transaction, and a test that loads every registered fixture
//! together (`tests/requests/public_fixtures.rs`) shows that they do not
//! collide.

use std::{collections::BTreeSet, fmt};

use chrono::{DateTime, Utc};
use futures_util::future::BoxFuture;
use sea_orm::{
    ConnectionTrait, DatabaseConnection, DatabaseTransaction, DbBackend, DbErr, Statement,
    TransactionTrait,
};
use serde_json::{Value, json};

/// The first id of the twin range. Fixture rows keep their ids below it,
/// and the twin of row `id` gets `id + TWIN_ID_OFFSET`. Far above every
/// legacy id (the largest are in the hundreds) and far below 2^53, so a
/// twin id is still exact as a JSON number (ADR 0005 §3).
pub const TWIN_ID_OFFSET: i64 = 1_000_000_000;

/// The `deleted_at` of every twin. Public reads only ask whether it is set
/// (ADR 0011 §3), so one fixed instant serves every fixture and keeps the
/// rows the same on every run.
pub const TWIN_DELETED_AT: &str = "2026-09-01T06:00:00Z";

/// The future a fixture's load function returns.
pub type LoadFuture<'w> = BoxFuture<'w, Result<(), DbErr>>;

/// A fixture's load function: it writes the fixture's rows, and the twin
/// of each public row, through the writer.
pub type Load = for<'w, 'db> fn(&'w mut FixtureWriter<'db>) -> LoadFuture<'w>;

/// One named fixture of public-api.md §17.1.
#[derive(Clone, Copy)]
pub struct Fixture {
    /// The name in the first column of its §17.1 table, for example
    /// `Backdated post`; `tests/requests/public_fixtures.rs` checks that
    /// the table has it.
    pub name: &'static str,
    /// Writes the rows. It runs inside the transaction of [`load`], once.
    pub load: Load,
}

impl fmt::Debug for Fixture {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Fixture")
            .field("name", &self.name)
            .finish_non_exhaustive()
    }
}

/// Every registered fixture. An endpoint slice adds the §17.1 fixtures its
/// tests read, each with the twins of its public rows.
pub const FIXTURES: &[Fixture] = &[];

/// The names of every registered fixture.
#[must_use]
pub fn fixture_names() -> Vec<&'static str> {
    FIXTURES.iter().map(|fixture| fixture.name).collect()
}

/// The id the twin of row `id` gets.
///
/// - `id`: the live row's id, below [`TWIN_ID_OFFSET`].
#[must_use]
pub const fn twin_id(id: i64) -> i64 {
    id + TWIN_ID_OFFSET
}

/// A twin that a fixture wrote.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Twin {
    /// The fixture that wrote it, by its §17.1 name. The global suite
    /// checks that each route lists a row whose twin one of the route's own
    /// fixtures wrote, so that the twin check has something to miss.
    pub fixture: &'static str,
    /// The table of both rows.
    pub table: String,
    /// The live row the twin copies.
    pub live_id: i64,
    /// The twin's own id, [`twin_id`] of `live_id`.
    pub id: i64,
}

/// What the fixtures' load functions write with: the transaction of
/// [`load`], the name of the fixture that is running, and the twins written
/// so far.
pub struct FixtureWriter<'db> {
    db: &'db DatabaseTransaction,
    fixture: &'static str,
    twins: Vec<Twin>,
}

impl FixtureWriter<'_> {
    /// The transaction to write rows on, through the models or with SQL.
    #[must_use]
    pub fn db(&self) -> &DatabaseTransaction {
        self.db
    }

    /// Writes the soft-deleted twin of row `id` of `table` and returns its
    /// id (the module documentation gives the convention).
    ///
    /// - `table`: a trashable table (one with `deleted_at`), unquoted.
    /// - `id`: the live row to copy, which the fixture has written already.
    ///
    /// # Errors
    ///
    /// A [`DbErr`] when the table has no `deleted_at`, the row does not
    /// exist, or the copy breaks a constraint that counts trashed rows; for
    /// that last case, see [`Self::twin_with`].
    pub async fn twin(&mut self, table: &str, id: i64) -> Result<i64, DbErr> {
        self.twin_with(table, id, json!({})).await
    }

    /// Like [`Self::twin`], with some columns of the copy set to other
    /// values. A unique rule that also counts trashed rows (ADR 0011 §3),
    /// such as `lower(users.email)`, needs a different value in the twin.
    ///
    /// - `table`: a trashable table (one with `deleted_at`), unquoted.
    /// - `id`: the live row to copy.
    /// - `overrides`: a JSON object of column names and values, written as
    ///   PostgreSQL reads JSON into a row (`jsonb_populate_record`). It may
    ///   not set `id` or `deleted_at`, which the convention sets.
    ///
    /// # Errors
    ///
    /// As [`Self::twin`], and when `overrides` is not an object or names a
    /// column the table does not have (PostgreSQL would ignore it).
    pub async fn twin_with(
        &mut self,
        table: &str,
        id: i64,
        overrides: Value,
    ) -> Result<i64, DbErr> {
        let fail = |what: String| DbErr::Custom(format!("twin of {table} row {id}: {what}"));
        if !(1..TWIN_ID_OFFSET).contains(&id) {
            return Err(fail(format!(
                "a fixture row's id is between 1 and {}",
                TWIN_ID_OFFSET - 1
            )));
        }
        let Value::Object(mut values) = overrides else {
            return Err(fail("the overrides are not a JSON object".to_owned()));
        };
        let columns = insertable_columns(self.db, table).await?;
        if !columns.iter().any(|column| column == "deleted_at") {
            return Err(fail(format!(
                "{table} has no deleted_at column; only trashable tables have twins \
                 (ADR 0011 §1)"
            )));
        }
        for key in values.keys() {
            if key == "id" || key == "deleted_at" {
                return Err(fail(format!("the overrides may not set {key}")));
            }
            if !columns.contains(key) {
                return Err(fail(format!("{table} has no column {key}")));
            }
        }
        let twin = twin_id(id);
        values.insert("id".to_owned(), json!(twin));
        values.insert("deleted_at".to_owned(), json!(TWIN_DELETED_AT));
        let table_name = quote_identifier(table);
        let list = columns
            .iter()
            .map(|column| quote_identifier(column))
            .collect::<Vec<_>>()
            .join(", ");
        // The row as JSON, with the overrides merged in, read back into a
        // row of the table's own type: every column keeps its value and
        // type, whatever the table has. Generated columns are not listed,
        // because PostgreSQL computes them itself.
        let sql = format!(
            "INSERT INTO {table_name} ({list}) \
             SELECT {list} FROM jsonb_populate_record(NULL::{table_name}, \
             (SELECT to_jsonb(source) FROM {table_name} AS source WHERE source.id = $1) \
             || $2::jsonb) RETURNING id"
        );
        let statement = Statement::from_sql_and_values(
            DbBackend::Postgres,
            sql,
            [id.into(), Value::Object(values).into()],
        );
        let exists = self
            .db
            .query_one_raw(Statement::from_sql_and_values(
                DbBackend::Postgres,
                format!("SELECT 1 FROM {table_name} WHERE id = $1"),
                [id.into()],
            ))
            .await?;
        if exists.is_none() {
            return Err(fail("the row does not exist; write it first".to_owned()));
        }
        let row = self
            .db
            .query_one_raw(statement)
            .await?
            .ok_or_else(|| fail("the copy returned no row".to_owned()))?;
        let written: i64 = row.try_get_by_index(0)?;
        self.twins.push(Twin {
            fixture: self.fixture,
            table: table.to_owned(),
            live_id: id,
            id: written,
        });
        Ok(written)
    }
}

/// The columns of `table` that an `INSERT` may set: every column that is
/// not generated, in table order.
async fn insertable_columns(db: &DatabaseTransaction, table: &str) -> Result<Vec<String>, DbErr> {
    let sql = "SELECT a.attname::text FROM pg_attribute AS a \
               WHERE a.attrelid = to_regclass($1) AND a.attnum > 0 \
               AND NOT a.attisdropped AND a.attgenerated = '' ORDER BY a.attnum";
    let rows = db
        .query_all_raw(Statement::from_sql_and_values(
            DbBackend::Postgres,
            sql,
            [quote_identifier(table).into()],
        ))
        .await?;
    if rows.is_empty() {
        return Err(DbErr::Custom(format!("there is no table {table}")));
    }
    rows.iter()
        .map(|row| row.try_get_by_index::<String>(0))
        .collect()
}

/// `name` as a quoted SQL identifier.
fn quote_identifier(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

/// The outcome of [`load`]: which fixtures ran and the twins they wrote.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Loaded {
    /// The fixtures, in the order they ran.
    pub fixtures: Vec<&'static str>,
    /// Every twin, in the order it was written.
    pub twins: Vec<Twin>,
}

impl Loaded {
    /// The twin ids of the rows of `table`, in the order they were written.
    ///
    /// - `table`: the table name as the fixtures passed it.
    #[must_use]
    pub fn twin_ids(&self, table: &str) -> Vec<i64> {
        self.twins
            .iter()
            .filter(|twin| twin.table == table)
            .map(|twin| twin.id)
            .collect()
    }
}

/// Why loading fixtures failed.
#[derive(Debug)]
pub enum FixtureError {
    /// The registry has two fixtures with one name.
    DuplicateRegistration(&'static str),
    /// A requested name is not registered.
    Unknown {
        /// The requested name.
        name: String,
        /// Every registered name.
        known: Vec<&'static str>,
    },
    /// A name was requested twice.
    RequestedTwice(String),
    /// A fixture's load function failed; nothing was written.
    Load {
        /// The fixture.
        fixture: &'static str,
        /// What failed.
        error: DbErr,
    },
    /// A live row has an id in the twin range.
    LiveRowInTwinRange {
        /// The table.
        table: String,
        /// The ids of its live rows from [`TWIN_ID_OFFSET`] up.
        ids: Vec<i64>,
    },
    /// The transaction itself, the checks or the sequence reset failed.
    Database(DbErr),
}

impl fmt::Display for FixtureError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DuplicateRegistration(name) => write!(
                f,
                "two fixtures are registered as `{name}`; each §17.1 name names one fixture"
            ),
            Self::Unknown { name, known } => write!(
                f,
                "no fixture is registered as `{name}`; register it in FIXTURES \
                 (tests/support/fixtures.rs) under its public-api.md §17.1 name. Registered: \
                 {known:?}"
            ),
            Self::RequestedTwice(name) => {
                write!(f, "the fixture `{name}` is requested twice; it loads once")
            }
            Self::Load { fixture, error } => {
                write!(
                    f,
                    "the fixture `{fixture}` failed, so no fixture was written: {error}"
                )
            }
            Self::LiveRowInTwinRange { table, ids } => write!(
                f,
                "{table} has live rows with ids from {TWIN_ID_OFFSET} up, the range of the \
                 soft-deleted twins: {ids:?}. Give fixture rows smaller ids"
            ),
            Self::Database(error) => write!(f, "loading the fixtures failed: {error}"),
        }
    }
}

impl From<DbErr> for FixtureError {
    fn from(error: DbErr) -> Self {
        Self::Database(error)
    }
}

/// Loads the registered fixtures `names` into the test's database, in that
/// order and in one transaction, and returns what they wrote.
///
/// - `db`: the test's pool (`ctx.db`).
/// - `names`: §17.1 names of registered fixtures, each at most once.
///
/// # Panics
///
/// With the message of [`FixtureError`] when loading fails; nothing is
/// written then.
pub async fn load(db: &DatabaseConnection, names: &[&str]) -> Loaded {
    try_load(FIXTURES, db, names)
        .await
        .unwrap_or_else(|error| panic!("{error}"))
}

/// [`load`] from a given registry, with the failure as a value.
///
/// - `registry`: the fixtures that may be named, normally [`FIXTURES`].
/// - `db`: the test's pool (`ctx.db`).
/// - `names`: names of fixtures in `registry`, each at most once.
///
/// # Errors
///
/// Every [`FixtureError`]; the transaction is rolled back, so the database
/// is as it was.
pub async fn try_load(
    registry: &[Fixture],
    db: &DatabaseConnection,
    names: &[&str],
) -> Result<Loaded, FixtureError> {
    let mut registered = BTreeSet::new();
    for fixture in registry {
        if !registered.insert(fixture.name) {
            return Err(FixtureError::DuplicateRegistration(fixture.name));
        }
    }
    let mut chosen = Vec::new();
    let mut requested = BTreeSet::new();
    for name in names {
        if !requested.insert(*name) {
            return Err(FixtureError::RequestedTwice((*name).to_owned()));
        }
        let fixture = registry
            .iter()
            .find(|fixture| fixture.name == *name)
            .ok_or_else(|| FixtureError::Unknown {
                name: (*name).to_owned(),
                known: registry.iter().map(|fixture| fixture.name).collect(),
            })?;
        chosen.push(*fixture);
    }

    let transaction = db.begin().await?;
    let mut writer = FixtureWriter {
        db: &transaction,
        fixture: "",
        twins: Vec::new(),
    };
    for fixture in &chosen {
        writer.fixture = fixture.name;
        if let Err(error) = (fixture.load)(&mut writer).await {
            // Dropping the transaction rolls it back; the explicit rollback
            // returns the connection at once.
            drop(writer);
            transaction.rollback().await?;
            return Err(FixtureError::Load {
                fixture: fixture.name,
                error,
            });
        }
    }
    let twins = writer.twins;
    if let Err(error) = check_and_reset_identities(&transaction).await {
        transaction.rollback().await?;
        return Err(error);
    }
    transaction.commit().await?;
    Ok(Loaded {
        fixtures: chosen.iter().map(|fixture| fixture.name).collect(),
        twins,
    })
}

/// The identity columns of the tables in the `public` schema, with whether
/// each table has a `deleted_at` column.
async fn identity_columns(db: &DatabaseTransaction) -> Result<Vec<(String, String, bool)>, DbErr> {
    let sql = "SELECT c.relname::text, a.attname::text, \
               EXISTS (SELECT 1 FROM pg_attribute AS d WHERE d.attrelid = c.oid \
                       AND d.attname = 'deleted_at' AND NOT d.attisdropped) \
               FROM pg_class AS c \
               JOIN pg_namespace AS n ON n.oid = c.relnamespace \
               JOIN pg_attribute AS a ON a.attrelid = c.oid \
               WHERE n.nspname = 'public' AND c.relkind = 'r' AND a.attidentity <> '' \
               AND NOT a.attisdropped ORDER BY 1, 2";
    db.query_all_raw(Statement::from_string(DbBackend::Postgres, sql))
        .await?
        .iter()
        .map(|row| {
            Ok((
                row.try_get_by_index(0)?,
                row.try_get_by_index(1)?,
                row.try_get_by_index(2)?,
            ))
        })
        .collect()
}

/// Checks the twin range on every table with an identity column and moves
/// each identity sequence past the largest id below [`TWIN_ID_OFFSET`].
///
/// A table without `deleted_at` has no twins, so none of its rows may sit
/// in the range; a table with it may keep only trashed rows there.
async fn check_and_reset_identities(db: &DatabaseTransaction) -> Result<(), FixtureError> {
    for (table, column, trashable) in identity_columns(db).await? {
        let table_name = quote_identifier(&table);
        let column_name = quote_identifier(&column);
        let live = if trashable {
            " AND deleted_at IS NULL"
        } else {
            ""
        };
        let rows = db
            .query_all_raw(Statement::from_sql_and_values(
                DbBackend::Postgres,
                format!(
                    "SELECT {column_name} FROM {table_name} WHERE {column_name} >= $1{live} \
                     ORDER BY 1 LIMIT 10"
                ),
                [TWIN_ID_OFFSET.into()],
            ))
            .await?;
        if !rows.is_empty() {
            let ids = rows
                .iter()
                .map(|row| row.try_get_by_index::<i64>(0))
                .collect::<Result<_, _>>()?;
            return Err(FixtureError::LiveRowInTwinRange { table, ids });
        }
        // `setval` only when the table has a row below the offset: with
        // none, the sequence still starts at 1.
        db.execute_raw(Statement::from_sql_and_values(
            DbBackend::Postgres,
            format!(
                "SELECT setval(pg_get_serial_sequence($1, $2), max({column_name})) \
                 FROM {table_name} WHERE {column_name} < $3 HAVING max({column_name}) IS NOT NULL"
            ),
            [
                table_name.clone().into(),
                column.clone().into(),
                TWIN_ID_OFFSET.into(),
            ],
        ))
        .await?;
    }
    Ok(())
}

/// Where `body` contains a twin: every object member `id` whose value is an
/// integer from [`TWIN_ID_OFFSET`] up, as `JSON pointer: id`.
///
/// Only twins have such ids (the module documentation), so this needs no
/// knowledge of the schema: a twin found anywhere, nested in a post's labels
/// or in a page of a list, is a trashed row that a public read let through.
///
/// - `body`: a parsed response body.
#[must_use]
pub fn twin_ids_in(body: &Value) -> Vec<String> {
    ids_in(body)
        .into_iter()
        .filter(|(_, id)| *id >= TWIN_ID_OFFSET)
        .map(|(pointer, id)| format!("{pointer}/id: {id}"))
        .collect()
}

/// The ids of the rows that `body` lists: every object member `id` whose
/// value is an integer below [`TWIN_ID_OFFSET`], each once, in ascending
/// order. The global suite compares them with the rows that have twins, to
/// make sure that an answer it checks for twins lists such a row at all.
///
/// - `body`: a parsed response body.
#[must_use]
pub fn row_ids_in(body: &Value) -> BTreeSet<i64> {
    ids_in(body)
        .into_iter()
        .map(|(_, id)| id)
        .filter(|id| *id < TWIN_ID_OFFSET)
        .collect()
}

/// Every object member `id` of `body` whose value is an integer, as the
/// JSON pointer of its object and the id, in document order.
fn ids_in(body: &Value) -> Vec<(String, i64)> {
    let mut found = Vec::new();
    walk_ids(body, &mut String::new(), &mut found);
    found
}

/// The recursion of [`ids_in`]; `pointer` is the JSON pointer of `value`.
fn walk_ids(value: &Value, pointer: &mut String, found: &mut Vec<(String, i64)>) {
    let length = pointer.len();
    match value {
        Value::Object(members) => {
            if let Some(id) = members.get("id").and_then(Value::as_i64) {
                found.push((pointer.clone(), id));
            }
            for (key, member) in members {
                pointer.push('/');
                pointer.push_str(&key.replace('~', "~0").replace('/', "~1"));
                walk_ids(member, pointer, found);
                pointer.truncate(length);
            }
        }
        Value::Array(items) => {
            for (index, item) in items.iter().enumerate() {
                pointer.push('/');
                pointer.push_str(&index.to_string());
                walk_ids(item, pointer, found);
                pointer.truncate(length);
            }
        }
        _ => {}
    }
}

/// The first-column names of the tables in public-api.md §17.1, the names
/// fixtures are registered under.
///
/// - `markdown`: the text of `docs/design/public-api.md`.
#[must_use]
pub fn section_17_1_names(markdown: &str) -> Vec<String> {
    markdown
        .lines()
        .skip_while(|line| !line.starts_with("### 17.1 "))
        .skip(1)
        .take_while(|line| !line.starts_with("### "))
        .filter_map(|line| {
            let cell = line.strip_prefix('|')?.split('|').next()?.trim();
            (!cell.is_empty() && cell != "Fixture" && !cell.starts_with("---"))
                .then(|| cell.to_owned())
        })
        .collect()
}

/// The instant of [`TWIN_DELETED_AT`].
///
/// # Panics
///
/// Never: the constant is RFC 3339, which a unit test checks.
#[must_use]
pub fn twin_deleted_at() -> DateTime<Utc> {
    DateTime::parse_from_rfc3339(TWIN_DELETED_AT)
        .expect("TWIN_DELETED_AT is RFC 3339")
        .with_timezone(&Utc)
}
