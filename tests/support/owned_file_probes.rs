//! `owned_file_probes`: a test-only entity that owns files in three
//! shapes, so the owned-files model and the `DeleteOwnedFiles` worker are
//! proven before the first upload slice registers a real column (ADR 0011
//! §6, ADR 0016 §3).
//!
//! [`create_table`] creates its table in the test's own database: a text
//! column `image` with one stored value (as `authors.image`), a text column
//! `index_image` that stores `index/<name>` (as `posts.index_image`), and a
//! `jsonb` array `images` (as `posts.images`, data-migration.md §6.1), plus
//! `deleted_at` for the trash. [`OWNERS`] registers the three columns, each
//! for its legacy folder. [`ProbeRevision`] is its snapshot type, and
//! [`append_revision`] writes one revision through `models::revisions`.
//! No migration creates the table, so it never reaches the schema snapshot.
//!
//! The file names are invented.

use backend3::{
    domain::{
        activity::Actor,
        media_rules::EntityImageFolder,
        owned_files::{FileOwner, OwnedPath},
        revision::{Reason, RevisionSnapshot},
    },
    models::revisions,
};
use sea_orm::{ConnectionTrait, DatabaseConnection, DbBackend, Statement, TransactionTrait, Value};
use serde::{Deserialize, Serialize};

/// The probe entity's table name, which is also its revisions'
/// `entity_type`.
pub const TABLE: &str = "owned_file_probes";

/// The test-only table.
const CREATE_TABLE: &str = "CREATE TABLE owned_file_probes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image text,
    index_image text,
    images jsonb NOT NULL DEFAULT '[]',
    deleted_at timestamptz
)";

/// The probe's three owned columns, as an upload slice registers its own.
pub static OWNERS: [FileOwner; 3] = [
    FileOwner {
        entity: TABLE,
        column: "image",
        folder: EntityImageFolder::AuthorImages,
    },
    FileOwner {
        entity: TABLE,
        column: "index_image",
        folder: EntityImageFolder::PostIndexImages,
    },
    FileOwner {
        entity: TABLE,
        column: "images",
        folder: EntityImageFolder::PostImages,
    },
];

/// Creates the `owned_file_probes` table in the test's database.
///
/// - `db`: the test's pool (`ctx.db`).
pub async fn create_table(db: &DatabaseConnection) {
    db.execute_unprepared(CREATE_TABLE)
        .await
        .expect("create owned_file_probes");
}

/// The revision snapshot of a probe: its three owned fields, each named
/// like its column, as `models::owned_files::files_of_record` needs.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProbeRevision {
    /// The stored value of its `image`, if any.
    pub image: Option<String>,
    /// The stored value of its `index_image` (`index/<name>`), if any.
    pub index_image: Option<String>,
    /// The stored values of its `images`, in order.
    pub images: Vec<String>,
}

impl RevisionSnapshot for ProbeRevision {
    const ENTITY_TYPE: &'static str = TABLE;
    const SCHEMA_VERSION: i32 = 1;
    const FIELDS: &'static [&'static str] = &["image", "index_image", "images"];
}

/// Inserts a probe row with `fields`, in the trash when `trashed`, and
/// returns its id. No revision is written.
///
/// - `db`: the test's pool.
/// - `fields`: the row's values.
/// - `trashed`: whether `deleted_at` is set.
pub async fn insert(db: &DatabaseConnection, fields: &ProbeRevision, trashed: bool) -> i64 {
    let images = serde_json::to_value(&fields.images).expect("a JSON array");
    let row = db
        .query_one_raw(Statement::from_sql_and_values(
            DbBackend::Postgres,
            "INSERT INTO owned_file_probes (image, index_image, images, deleted_at) \
             VALUES ($1, $2, $3, CASE WHEN $4 THEN now() END) RETURNING id",
            [
                Value::from(fields.image.clone()),
                Value::from(fields.index_image.clone()),
                Value::from(images),
                Value::from(trashed),
            ],
        ))
        .await
        .expect("insert a probe")
        .expect("one row");
    row.try_get_by_index(0).expect("the id")
}

/// Writes `fields` over probe `id`, with no revision.
///
/// - `db`: the test's pool.
/// - `id`: the probe.
/// - `fields`: its values after the write.
pub async fn update(db: &DatabaseConnection, id: i64, fields: &ProbeRevision) {
    let images = serde_json::to_value(&fields.images).expect("a JSON array");
    db.execute_raw(Statement::from_sql_and_values(
        DbBackend::Postgres,
        "UPDATE owned_file_probes SET image = $1, index_image = $2, images = $3 WHERE id = $4",
        [
            Value::from(fields.image.clone()),
            Value::from(fields.index_image.clone()),
            Value::from(images),
            Value::from(id),
        ],
    ))
    .await
    .expect("update a probe");
}

/// Appends the next revision of probe `id`, with `fields` as its snapshot,
/// as a system update (`models::revisions::append`).
///
/// - `db`: the test's pool; the revision is written in a transaction of its
///   own, which locks the probe's row as every save does.
/// - `id`: the probe.
/// - `fields`: the snapshot.
pub async fn append_revision(db: &DatabaseConnection, id: i64, fields: &ProbeRevision) {
    let txn = db.begin().await.expect("begin");
    revisions::append(&txn, Actor::System, id, Reason::Update, fields, None)
        .await
        .expect("append a revision");
    txn.commit().await.expect("commit");
}

/// Writes a revision of `entity_type` record `entity_id` with a snapshot
/// given as JSON, bypassing the snapshot types: a revision of an older or
/// newer snapshot shape, of a broken one, or of another entity, which no
/// type of the test writes.
///
/// - `db`: the test's pool.
/// - `entity_type`: the revision's entity type.
/// - `entity_id`: its record.
/// - `version`: its stored `schema_version`, from 1.
/// - `snapshot`: the stored snapshot, a JSON object.
pub async fn insert_raw_revision(
    db: &DatabaseConnection,
    entity_type: &str,
    entity_id: i64,
    version: i32,
    snapshot: serde_json::Value,
) {
    db.execute_raw(Statement::from_sql_and_values(
        DbBackend::Postgres,
        "INSERT INTO revisions (entity_type, entity_id, revision_no, reason, schema_version, \
         snapshot) VALUES ($1, $2, (SELECT COALESCE(MAX(revision_no), 0) + 1 FROM revisions \
         WHERE entity_type = $1 AND entity_id = $2), 'update', $3, $4)",
        [
            Value::from(entity_type.to_owned()),
            Value::from(entity_id),
            Value::from(version),
            Value::from(snapshot),
        ],
    ))
    .await
    .expect("insert a raw revision");
}

/// A new invented entity image name, `<32 hex>.jpg`, unique per call.
pub fn new_name() -> String {
    format!("{}.jpg", sea_orm::prelude::Uuid::new_v4().simple())
}

/// The owned path of the file `name` in `folder`, the stored value of
/// [`stored`] below the folder's disk.
///
/// - `folder`: the entity image folder.
/// - `name`: the file name.
pub fn path(folder: EntityImageFolder, name: &str) -> OwnedPath {
    OwnedPath::parse(&format!("{}/{name}", folder.path())).expect("an owned path")
}

/// The value a row of `folder`'s owner stores for the file `name`:
/// `index/<name>` for a post's index image, `<name>` otherwise.
///
/// - `folder`: the entity image folder.
/// - `name`: the file name.
pub fn stored(folder: EntityImageFolder, name: &str) -> String {
    path(folder, name).stored_value().to_owned()
}
