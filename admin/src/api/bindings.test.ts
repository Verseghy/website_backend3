// @vitest-environment node
/**
 * No ts-rs binding has a `bigint` (ADR 0005 §3, "What must be true in code
 * and tests").
 *
 * Why: ts-rs writes a Rust `i64` or `u64` as TypeScript's `bigint` unless the
 * field says `#[ts(type = "number")]`. `JSON.parse` never makes a `bigint`,
 * so such a binding would promise the admin a type that no answer has, and
 * a screen written against it would compare a number with a bigint and miss
 * every match. The Rust DTO tests check their own declarations; this test
 * reads every file that ts-rs wrote into `src/bindings/`, so a DTO that a
 * slice adds without the override fails here, in the admin's own gate,
 * whatever its Rust tests check.
 */
import { readdirSync, readFileSync } from "node:fs"
import { join, resolve, sep } from "node:path"

import { describe, expect, it } from "vitest"

const BINDINGS = resolve(import.meta.dirname, "../bindings")

/**
 * The TypeScript files ts-rs wrote, in every subdirectory too.
 *
 * The walk is recursive because ts-rs writes a type of another crate into a
 * directory named after it (for example `serde_json/JsonValue.ts`), and a
 * `bigint` there would reach the admin as surely as one at the top level.
 *
 * @returns their paths relative to `src/bindings/`, with `/` separators,
 *   sorted.
 */
function bindingFiles(): string[] {
  return readdirSync(BINDINGS, { recursive: true, encoding: "utf8" })
    .map((path) => path.split(sep).join("/"))
    .filter((path) => path.endsWith(".ts"))
    .sort()
}

/**
 * The lines of a binding that use the `bigint` type.
 *
 * Comments are blanked first, line breaks kept, so the documentation that
 * ts-rs copies from a Rust doc comment may mention the word: ts-rs writes
 * them as `/** … *\/` blocks, and its header as one `//` line.
 *
 * @param text - the binding's source.
 * @returns the 1-based numbers of the lines that use `bigint`.
 */
function bigintLines(text: string): number[] {
  const code = text
    .replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, " "))
    .replace(/^[ \t]*\/\/.*$/gm, "")
  return code
    .split("\n")
    .flatMap((line, index) => (/\bbigint\b/.test(line) ? [index + 1] : []))
}

describe("bigintLines", () => {
  it("finds the type wherever a declaration uses it", () => {
    expect(
      bigintLines(
        [
          "export type A = { id: bigint, };",
          "export type B = { ids: Array<bigint>, };",
          "export type C = { total: number | bigint, };",
        ].join("\n")
      )
    ).toEqual([1, 2, 3])
  })

  it("ignores documentation and ts-rs's header, and other words", () => {
    expect(
      bigintLines(
        [
          "// This file was generated by ts-rs. A bigint here is a comment.",
          "/**",
          " * Never a bigint (ADR 0005 §3).",
          " */",
          "export type A = { /** not a bigint */ id: number, bigints: number, };",
        ].join("\n")
      )
    ).toEqual([])
  })
})

describe("the ts-rs bindings", () => {
  it('never use bigint: every 64-bit integer field carries #[ts(type = "number")]', () => {
    const offenders = bindingFiles().flatMap((name) =>
      bigintLines(readFileSync(join(BINDINGS, name), "utf8")).map(
        (line) => `src/bindings/${name}:${line}`
      )
    )
    expect(
      offenders,
      `Add #[ts(type = "number")] to the i64/u64 fields of these DTOs and run the Rust tests to rewrite the bindings:\n${offenders.join("\n")}`
    ).toEqual([])
  })

  it("reads the bindings (guards against a broken walk)", () => {
    const files = bindingFiles()
    expect(files.length).toBeGreaterThanOrEqual(10)
    // The list contract's bindings, whose `id` and `total` are 64-bit on the
    // server.
    expect(files).toEqual(
      expect.arrayContaining(["LabelResponse.ts", "ListResponse.ts"])
    )
  })
})
