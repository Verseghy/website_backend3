//! Fat Active Record models on Sea-ORM (ADR 0008, rule 4).
//!
//! Each vertical slice adds its migration, runs `cargo loco db entities` to
//! regenerate `_entities/` (never edited by hand), and adds its model module
//! here. Finders live on `impl Model`, state transitions on
//! `impl ActiveModel`, and both take the connection explicitly. Database code
//! that several callers share and no entity owns, such as `task_lock`, is a
//! model module without an entity (rule 5).
//!
//! - [`activity_log`]: the append-only activity log (ADR 0011 §5).
//! - [`job_queue`]: Loco's job queue table, read for `/metrics`; a model
//!   module without an entity.
//! - [`labels`]: the post labels (parity LBL-01), with the live-row finders
//!   every read of them goes through (ADR 0011 §3).
//! - [`list_page`]: one page of an admin list and its total, read in one
//!   snapshot (the shared admin list contract); a model module without an
//!   entity.
//! - [`media`]: the uploads volume: an upload streamed to staging, optimised
//!   and renamed into place (ADR 0015 §6, §7); a model module without an
//!   entity.
//! - [`owned_files`]: whether anything still refers to an owned file, and
//!   the removal of those nothing refers to (ADR 0011 §6, ADR 0016 §3); a
//!   model module without an entity.
//! - [`revisions`]: the append-only revisions of every admin-editable
//!   entity, and the save that writes a revision with its activity entry
//!   (ADR 0011 §4, §7).
//! - [`roles`]: the four roles that a migration seeds (ADR 0007 §3).
//! - [`task_lock`]: the advisory lock every task runs under (ADR 0016 §4); a
//!   model module without an entity.
//! - [`user_permissions`]: each account's extra grants (ADR 0007 §3).
//! - [`user_roles`]: the roles each account holds (ADR 0007 §3).
//! - [`users`]: the admin accounts (ADR 0006), with the roles and grants
//!   they hold (`users::Model::grants`).

/// The Sea-ORM entities, generated from the migrated schema by
/// `cargo loco db entities` (sea-orm-cli). Regenerate them after every
/// migration; never edit them by hand.
///
/// The generator writes no doc comments, and every regeneration would drop
/// any added by hand, so the workspace's `missing_docs` lint is allowed for
/// this module only. The tables and columns are documented in their
/// migrations and in the ADRs that define them; the model modules beside
/// this one document the methods built on them.
#[allow(
    missing_docs,
    reason = "generated by sea-orm-cli, which writes no doc comments; see the migrations"
)]
pub mod _entities;
pub mod activity_log;
pub mod job_queue;
pub mod labels;
pub mod list_page;
pub mod media;
pub mod owned_files;
pub mod revisions;
pub mod roles;
pub mod task_lock;
pub mod user_permissions;
pub mod user_roles;
pub mod users;
