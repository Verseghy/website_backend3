//! Fat Active Record models on Sea-ORM (ADR 0008, rule 4).
//!
//! Each vertical slice adds its migration, runs `cargo loco db entities` to
//! regenerate `_entities/` (never edited by hand), and adds its model module
//! here. Finders live on `impl Model`, state transitions on
//! `impl ActiveModel`, and both take the connection explicitly. Database code
//! that several callers share and no entity owns, such as `task_lock`, is a
//! model module without an entity (rule 5).
//!
//! - [`task_lock`]: the advisory lock every task runs under (ADR 0016 §4); a
//!   model module without an entity.
//! - [`users`]: the admin accounts (ADR 0006).

/// The Sea-ORM entities, generated from the migrated schema by
/// `cargo loco db entities` (sea-orm-cli). Regenerate them after every
/// migration; never edit them by hand.
///
/// The generator writes no doc comments, and every regeneration would drop
/// any added by hand, so the workspace's `missing_docs` lint is allowed for
/// this module only. The tables and columns are documented in their
/// migrations and in the ADRs that define them; the model modules beside
/// this one document the methods built on them.
#[allow(
    missing_docs,
    reason = "generated by sea-orm-cli, which writes no doc comments; see the migrations"
)]
pub mod _entities;
pub mod task_lock;
pub mod users;
