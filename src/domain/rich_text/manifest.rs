//! The policy manifest (editor.md §3.9): content-v1 written out as the two
//! files the admin imports, `policy.json` and `css-vectors.jsonl`.
//!
//! content-v1 is defined once, as data, in [`super::policy`] and
//! [`super::css::grammar`] (ADR 0013 §1). The admin's paste filter, its
//! `canonicalStyle` and the custom `TipTap` attributes have to follow the same
//! rules in TypeScript, so they read them from a file instead of a second
//! hand-written copy: this module renders that file from the Rust tables,
//! and the `rich_text_manifest` task writes it, with the CSS vectors, to
//! `admin/src/rich-text/`, where both are committed. The Contract CI job runs
//! the task and fails when a committed copy differs from its output, or when
//! the tag list holds a tag that editor.md §3.5 forbids.
//!
//! The rendering is deterministic: every list keeps the order of its table,
//! every map is written in that order too (never through a hash map), and
//! the JSON is pretty-printed with two spaces and ends in a newline, so a
//! policy change shows up as a reviewable diff of the committed file.
//!
//! [`policy_json`] refuses tables that would describe a broken policy rather
//! than write them: a forbidden tag in the tag list (editor.md §3.5, "Never
//! in the tag list"), or an element whose `style` attribute and CSS grammar
//! do not come together. The deployment-specific values (the embed
//! providers, the image prefix and the own hosts) come from the
//! [`SanitizePolicy`] it is given, which it validates first; the task always
//! passes [`SanitizePolicy::content_v1`], because the committed copy must be
//! the same in every environment. The work bounds of the policy (input
//! size, nesting depth, output size) are not part of the dialect and are not
//! written.
//!
//! The task's one argument, the output directory, is read here too
//! ([`output_dir`]), so that its rule is pure and tested like the rest.
//!
//! The field-by-field description of `policy.json` is in editor.md §3.9.

