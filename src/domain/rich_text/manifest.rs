/// The file name of the policy, as the admin imports it.
pub const POLICY_FILE: &str = "policy.json";

/// The file name of the CSS vectors ([`super::css::vectors`]).
pub const CSS_VECTORS_FILE: &str = "css-vectors.jsonl";

/// The `$comment` member of `policy.json`, which tells a reader of the file
/// where it comes from and that it is never edited by hand.
pub const POLICY_COMMENT: &str = "Generated by `cargo loco task rich_text_manifest` from the \
     content-v1 policy in src/domain/rich_text/ (docs/design/editor.md §3.9). Never edit it by \
     hand: the Contract CI job fails when it differs from the task's output.";

/// The content-v1 tables a manifest is rendered from. [`PolicyTables::CONTENT_V1`]
/// is the only value outside tests; the struct exists so that a test can
/// hand [`policy_json`] tables that break a rule and see it refuse them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PolicyTables<'a> {
    /// The elements with their attributes in canonical order
    /// ([`super::policy::ELEMENTS`]).
    pub elements: &'a [ElementRule],
    /// The per-element CSS grammar ([`super::css::grammar::ELEMENT_STYLES`]).
    pub element_styles: &'a [ElementStyle],
    /// The elements removed together with their content
    /// ([`super::policy::REMOVED_WITH_CONTENT`]).
    pub removed_with_content: &'a [&'static str],
    /// The tags that must never be in the tag list
    /// ([`super::policy::FORBIDDEN_TAGS`]).
    pub forbidden_tags: &'a [&'static str],
}

impl PolicyTables<'static> {
    /// The tables of content-v1.
    pub const CONTENT_V1: Self = Self {
        elements: ELEMENTS,
        element_styles: ELEMENT_STYLES,
        removed_with_content: REMOVED_WITH_CONTENT,
        forbidden_tags: FORBIDDEN_TAGS,
    };
}

/// Why a manifest was not rendered.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ManifestError {
    /// The deployment-specific part of the policy is not valid.
    #[error("the rich-text policy is not valid: {0}")]
    Policy(#[from] PolicyError),
    /// The tag list holds tags that editor.md §3.5 forbids.
    #[error(
        "the content-v1 tag list contains {tags:?}, which must never be in it: their parsing \
         depends on the scripting flag, raw text or quirks mode (editor.md §3.5). Remove them \
         from src/domain/rich_text/policy.rs"
    )]
    ForbiddenTags {
        /// The forbidden tags found, in tag-list order.
        tags: Vec<String>,
    },
    /// An element's `style` attribute and its CSS grammar do not match: one
    /// of them is missing, or the grammar names an element that is not in
    /// the tag list.
    #[error(
        "the `style` of `{element}` is inconsistent: {problem} (src/domain/rich_text/policy.rs \
         and css/grammar.rs)"
    )]
    InconsistentStyle {
        /// The element.
        element: String,
        /// What does not match.
        problem: String,
    },
}

/// The directory the `rich_text_manifest` task writes to when it is given no
/// `dir:` argument: the admin's committed copy, relative to the repository
/// root, from where the task is run (editor.md §3.9).
pub const DEFAULT_OUTPUT_DIR: &str = "admin/src/rich-text";

/// The one argument the task accepts, as `dir:<directory>`.
pub const OUTPUT_DIR_ARGUMENT: &str = "dir";

/// A `rich_text_manifest` argument that cannot be used.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ArgumentError {
    /// Arguments other than `dir`, which would otherwise be ignored without
    /// a word (a typo such as `dri:` would write to the default directory).
    #[error(
        "unknown argument {keys:?}: the only argument is `dir:<directory>`, the directory to \
         write policy.json and css-vectors.jsonl to (default: {DEFAULT_OUTPUT_DIR})"
    )]
    Unknown {
        /// The unknown keys, in sorted order.
        keys: Vec<String>,
    },
    /// `dir:` with nothing after the colon.
    #[error("`dir:` needs a directory, for example `dir:{DEFAULT_OUTPUT_DIR}`")]
    EmptyDir,
}

/// The output directory that the task's `key:value` arguments ask for.
///
/// - `arguments`: the task's arguments, as Loco's `Vars::cli` holds them.
///   Loco keeps the last of two arguments with the same key.
///
/// # Errors
///
/// [`ArgumentError::Unknown`] for any key other than [`OUTPUT_DIR_ARGUMENT`],
/// and [`ArgumentError::EmptyDir`] for an empty directory.
pub fn output_dir(arguments: &BTreeMap<String, String>) -> Result<&str, ArgumentError> {
    let unknown: Vec<String> = arguments
        .keys()
        .filter(|key| key.as_str() != OUTPUT_DIR_ARGUMENT)
        .cloned()
        .collect();
    if !unknown.is_empty() {
        return Err(ArgumentError::Unknown { keys: unknown });
    }
    match arguments.get(OUTPUT_DIR_ARGUMENT).map(String::as_str) {
        None => Ok(DEFAULT_OUTPUT_DIR),
        Some("") => Err(ArgumentError::EmptyDir),
        Some(dir) => Ok(dir),
    }
}

/// One file of the manifest, ready to be written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ManifestFile {
    /// The file name, without a directory.
    pub name: &'static str,
    /// The complete contents, ending in a newline.
    pub contents: String,
}

/// The tags of `tags` that editor.md §3.5 forbids in the tag list, in their
/// order. The names are compared in ASCII lower case, because the HTML
/// parser lower-cases tag names, so `Script` is the `script` element.
///
/// - `tags`: tag names, as a policy table or a manifest file lists them.
/// - `forbidden`: the forbidden names, lower-case
///   ([`super::policy::FORBIDDEN_TAGS`] outside tests).
#[must_use]
pub fn forbidden_tags_in<'a>(tags: &[&'a str], forbidden: &[&str]) -> Vec<&'a str> {
    tags.iter()
        .copied()
        .filter(|tag| forbidden.contains(&tag.to_ascii_lowercase().as_str()))
        .collect()
}

/// `policy.json`: the content-v1 tables and the URL rules of `policy`, as
/// pretty-printed JSON ending in a newline.
///
/// - `tables`: the tables to render, [`PolicyTables::CONTENT_V1`] outside
///   tests.
/// - `policy`: supplies the embed providers, the image path prefix and the
///   own hosts. It is validated first.
///
/// # Errors
///
/// [`ManifestError::Policy`] when `policy` fails [`SanitizePolicy::validate`],
/// [`ManifestError::ForbiddenTags`] when the tag list holds a forbidden tag,
/// and [`ManifestError::InconsistentStyle`] when an element has a `style`
/// attribute without a CSS grammar, a grammar without a `style` attribute,
/// or a grammar names an element that is not in the tag list.
///
/// # Panics
///
/// Never: the document holds only strings, numbers, booleans, lists and
/// maps with string keys, which always serialise.
pub fn policy_json(
    tables: &PolicyTables<'_>,
    policy: &SanitizePolicy,
) -> Result<String, ManifestError> {
    policy.validate()?;
    let tags: Vec<&str> = tables.elements.iter().map(|element| element.name).collect();
    let forbidden = forbidden_tags_in(&tags, tables.forbidden_tags);
    if !forbidden.is_empty() {
        return Err(ManifestError::ForbiddenTags {
            tags: forbidden.into_iter().map(str::to_owned).collect(),
        });
    }
    check_styles(tables)?;

    let document = Document {
        comment: POLICY_COMMENT,
        policy_version: POLICY_VERSION,
        tags,
        elements: Elements(tables),
        removed_with_content: tables.removed_with_content,
        removed_by_namespace_check: AMMONIA_FOREIGN_TAGS,
        forbidden_tags: tables.forbidden_tags,
        css: Css {
            alphabet: STYLE_ALPHABET,
            border: Border {
                styles: BORDER_STYLES,
                width_keywords: WidthKeywords(BORDER_WIDTH_KEYWORDS),
                initial: SideView::of(Side::INITIAL),
                unset: SideView::of(Side::UNSET),
                max_width: Number(BORDER_WIDTH_MAX),
            },
        },
        urls: urls(policy),
    };
    // The document holds only strings, numbers, booleans, lists and maps
    // with string keys, which always serialise.
    let mut json = serde_json::to_string_pretty(&document).expect("the manifest serialises");
    json.push('\n');
    Ok(json)
}

/// Both files of the manifest, `policy.json` and `css-vectors.jsonl`, in
/// that order.
///
/// - `tables`: as for [`policy_json`].
/// - `policy`: as for [`policy_json`].
///
/// # Errors
///
/// Every error of [`policy_json`].
pub fn manifest_files(
    tables: &PolicyTables<'_>,
    policy: &SanitizePolicy,
) -> Result<[ManifestFile; 2], ManifestError> {
    Ok([
        ManifestFile {
            name: POLICY_FILE,
            contents: policy_json(tables, policy)?,
        },
        ManifestFile {
            name: CSS_VECTORS_FILE,
            contents: css_vectors_jsonl(),
        },
    ])
}

/// Refuses an element whose `style` attribute and CSS grammar do not come
/// together, and a grammar for an element outside the tag list.
fn check_styles(tables: &PolicyTables<'_>) -> Result<(), ManifestError> {
    let inconsistent = |element: &str, problem: &str| ManifestError::InconsistentStyle {
        element: element.to_owned(),
        problem: problem.to_owned(),
    };
    for element in tables.elements {
        let has_attribute = element.attribute("style").is_some();
        let has_grammar = style_of(tables, element.name).is_some();
        if has_attribute && !has_grammar {
            return Err(inconsistent(
                element.name,
                "it has a `style` attribute but no CSS grammar",
            ));
        }
        if has_grammar && !has_attribute {
            return Err(inconsistent(
                element.name,
                "it has a CSS grammar but no `style` attribute",
            ));
        }
    }
    for style in tables.element_styles {
        if !tables
            .elements
            .iter()
            .any(|element| element.name == style.element)
        {
            return Err(inconsistent(
                style.element,
                "it has a CSS grammar but is not in the tag list",
            ));
        }
    }
    Ok(())
}

fn style_of<'a>(tables: &PolicyTables<'a>, element: &str) -> Option<&'a ElementStyle> {
    tables
        .element_styles
        .iter()
        .find(|style| style.element == element)
}

fn urls(policy: &SanitizePolicy) -> Urls<'_> {
    Urls {
        schemes: URL_SCHEMES,
        own_hosts: &policy.own_hosts,
        storage_path_prefix: STORAGE_PATH_PREFIX,
        image: Image {
            path_prefix: &policy.image_path_prefix,
            extensions: IMAGE_EXTENSIONS,
        },
        link: Link {
            forbidden_storage_extensions: FORBIDDEN_STORAGE_LINK_EXTENSIONS,
        },
        embed: Embed {
            scheme: EMBED_SCHEME,
            id_alphabet: EMBED_ID_ALPHABET,
            providers: policy
                .embed_providers
                .iter()
                .map(|provider| Provider {
                    hosts: &provider.hosts,
                    path_prefix: &provider.path_prefix,
                    query: provider
                        .query
                        .parameters()
                        .iter()
                        .map(|parameter| QueryParameter {
                            name: parameter.name,
                            value: match parameter.value {
                                EmbedQueryValue::Digits => "digits",
                                EmbedQueryValue::Id => "id",
                            },
                        })
                        .collect(),
                })
                .collect(),
        },
    }
}

// The serialised shape. These are views over the policy tables, not domain
// types: they borrow the tables and exist only to fix the member names and
// their order in the file (editor.md §3.9).

#[derive(Serialize)]
struct Document<'a> {
    #[serde(rename = "$comment")]
    comment: &'static str,
    policy_version: &'static str,
    tags: Vec<&'static str>,
    elements: Elements<'a>,
    removed_with_content: &'a [&'static str],
    /// The second removed-with-content row of editor.md §3.5: the names
    /// ammonia's namespace check removes from the HTML namespace. They are
    /// ammonia's lists, not a policy table, but the admin's paste filter has
    /// to remove the same elements with their content.
    removed_by_namespace_check: &'static [&'static str],
    forbidden_tags: &'a [&'static str],
    css: Css,
    urls: Urls<'a>,
}

/// The elements as a map from tag name to its rules, in tag-list order.
/// `serde_json` writes a map's entries in the order they are given, so the
/// order does not depend on a hash seed.
struct Elements<'a>(&'a PolicyTables<'a>);

impl Serialize for Elements<'_> {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let tables = self.0;
        serializer.collect_map(tables.elements.iter().map(|element| {
            let view = ElementView {
                attributes: element
                    .attributes
                    .iter()
                    .map(|attribute| AttributeView {
                        name: attribute.name,
                        value: value_view(attribute.rule),
                    })
                    .collect(),
                style: style_of(tables, element.name).map(|style| {
                    style
                        .properties
                        .iter()
                        .map(property_view)
                        .collect::<Vec<_>>()
                }),
            };
            (element.name, view)
        }))
    }
}

#[derive(Serialize)]
struct ElementView {
    attributes: Vec<AttributeView>,
    style: Option<Vec<PropertyView>>,
}

#[derive(Serialize)]
struct AttributeView {
    name: &'static str,
    value: ValueView,
}

/// [`ValueRule`] in the file: `{"kind": ...}` plus the rule's parameters.
#[derive(Serialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum ValueView {
    Style,
    Text,
    Marker,
    Integer {
        min: u32,
        max: u32,
        omitted: Option<u32>,
    },
    IntegerOrFull {
        min: u32,
        max: u32,
        full: &'static str,
    },
    Enumerated {
        values: &'static [&'static str],
        omitted: Option<&'static str>,
    },
    Forced {
        value: &'static str,
    },
    LinkRel {
        value: &'static str,
    },
    ImageSrc,
    EmbedSrc,
    LinkHref,
}

fn value_view(rule: ValueRule) -> ValueView {
    match rule {
        ValueRule::Style => ValueView::Style,
        ValueRule::Text => ValueView::Text,
        ValueRule::Marker => ValueView::Marker,
        ValueRule::Integer { min, max, default } => ValueView::Integer {
            min,
            max,
            omitted: default,
        },
        ValueRule::IntegerOrFull { min, max } => ValueView::IntegerOrFull {
            min,
            max,
            full: IFRAME_FULL_WIDTH,
        },
        ValueRule::Enumerated { values, default } => ValueView::Enumerated {
            values,
            omitted: default,
        },
        ValueRule::Forced(value) => ValueView::Forced { value },
        // ammonia's `link_rel` writes it; the file gives the one value.
        ValueRule::LinkRel => ValueView::LinkRel { value: LINK_REL },
        ValueRule::ImageSrc => ValueView::ImageSrc,
        ValueRule::EmbedSrc => ValueView::EmbedSrc,
        ValueRule::LinkHref => ValueView::LinkHref,
    }
}

#[derive(Serialize)]
struct PropertyView {
    property: &'static str,
    grammar: GrammarView,
    role: &'static str,
    presence: &'static str,
    provisional: Option<&'static str>,
}

/// [`Grammar`] in the file: `{"kind": ...}` plus the grammar's parameters.
#[derive(Serialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum GrammarView {
    Keyword {
        values: &'static [&'static str],
        omitted: Option<&'static str>,
    },
    Px {
        min: Number,
        max: Number,
    },
    AutoOrPx {
        min: Number,
        max: Number,
    },
    Em {
        min: Number,
        max: Number,
    },
    Colour {
        opaque_only: bool,
    },
    BorderSide,
    BorderWidths,
    BorderStyles,
    BorderColours,
    Locked {
        value: &'static str,
    },
}

fn property_view(rule: &PropertyRule) -> PropertyView {
    let grammar = match rule.grammar {
        Grammar::Keyword { values, omitted } => GrammarView::Keyword { values, omitted },
        Grammar::Px { min, max } => GrammarView::Px {
            min: Number(min),
            max: Number(max),
        },
        Grammar::AutoOrPx { min, max } => GrammarView::AutoOrPx {
            min: Number(min),
            max: Number(max),
        },
        Grammar::Em { min, max } => GrammarView::Em {
            min: Number(min),
            max: Number(max),
        },
        Grammar::Colour { opaque_only } => GrammarView::Colour { opaque_only },
        Grammar::BorderSide => GrammarView::BorderSide,
        Grammar::BorderWidths => GrammarView::BorderWidths,
        Grammar::BorderStyles => GrammarView::BorderStyles,
        Grammar::BorderColours => GrammarView::BorderColours,
        Grammar::Locked(value) => GrammarView::Locked { value },
    };
    PropertyView {
        property: rule.name,
        grammar,
        role: match rule.role {
            Role::Stored => "stored",
            Role::InputOnly => "input_only",
        },
        presence: match rule.presence {
            Presence::Optional => "optional",
            Presence::Always => "always",
            Presence::WhenSized => "when_sized",
        },
        provisional: rule.provisional.map(|reason| match reason {
            Provisional::ExcelBorderWeights => "excel_border_weights",
            Provisional::ExcelGeneralAlignment => "excel_general_alignment",
            Provisional::ExcelVerticalAlignment => "excel_vertical_alignment",
        }),
    }
}

/// A [`Hundredths`] as a JSON number: an integer when it is whole (`20`),
/// otherwise a decimal (`0.5`), so the file shows the values of editor.md
/// §3.3 as they are written there.
#[derive(Clone, Copy)]
struct Number(Hundredths);

impl Serialize for Number {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let hundredths = self.0.hundredths();
        if hundredths.is_multiple_of(100) {
            serializer.serialize_u32(hundredths / 100)
        } else {
            serializer.serialize_f64(f64::from(hundredths) / 100.0)
        }
    }
}

#[derive(Serialize)]
struct Css {
    alphabet: &'static str,
    border: Border,
}

#[derive(Serialize)]
struct Border {
    styles: &'static [&'static str],
    width_keywords: WidthKeywords,
    /// [`Side::INITIAL`]: what `border` and `border-<side>` give each part
    /// they leave out (editor.md §7.3).
    initial: SideView,
    /// [`Side::UNSET`]: what a part that no declaration set keeps, the
    /// page's `border: 0` reset (editor.md §7.3; the maintainer kept the
    /// 0 px width as built, research: DECISIONS R23, D118).
    unset: SideView,
    max_width: Number,
}

/// A [`Side`] in the file: `{width, style, colour}`, the width in px and the
/// colour as the canonical writer spells it.
#[derive(Serialize)]
struct SideView {
    width: Number,
    style: &'static str,
    colour: String,
}

impl SideView {
    fn of(side: Side) -> Self {
        Self {
            width: Number(side.width),
            style: side.style,
            colour: side.colour.to_string(),
        }
    }
}

/// The border-width keywords as a map from keyword to px, in table order.
struct WidthKeywords(&'static [(&'static str, Hundredths)]);

impl Serialize for WidthKeywords {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.collect_map(self.0.iter().map(|&(keyword, px)| (keyword, Number(px))))
    }
}

